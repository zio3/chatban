/** #197: チャットに番号だけを打ったときに、そのカードを開くための判定。
 *
 * 「検索窓が欲しい、とくに番号でアクセスしたいケースが増えてきた」という要望に対して、
 * **専用の検索窓は作らない**。チャットは常設 (#74) なのでどこからでも打てるし、
 * 「会話がそのままタスク管理になる」という作りに素直に乗る。
 *
 * ここで拾うのは**番号だけの発言**に限る。`#193 を見せて` のような文は対象外で、
 * 普通にLLMへ渡す — 番号を含む文の意図まで正規表現で当てにいくと、
 * 「話しかけたのに勝手に画面が動く」ほうの事故になる。
 */

/** 番号だけの発言なら、そのカードID。違えば null。
 *
 * 拾う形: `193` / `#193` / `＃193` / 全角数字 / 前後の空白。
 * 日本語入力のままだと `＃` や全角数字になるので、そこは吸収する
 * (打ち直しを強いるほうが、正規表現を1文字広げるより高くつく)。
 *
 * 拾わない形: `#193 を見せて` (文)、`-1` (負数)、`1.5` (小数)、`` (空)。
 * 桁は 15 文字までに制限する — それを超える入力はカードIDではありえず、
 * Number() が丸めた値でうっかり別のカードを開く経路を作らないため。
 */
export function parseTaskJump(text: string): number | null {
  // 全角の井桁と数字を半角へ寄せてから見る
  const normalized = text
    .trim()
    .replace(/＃/g, "#")
    .replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));
  const m = /^#?([0-9]{1,15})$/.exec(normalized);
  if (!m) return null;
  const id = Number(m[1]);
  // `0` や `#000` は存在しないIDなので弾く (IDは1から振られる)
  return Number.isSafeInteger(id) && id > 0 ? id : null;
}
