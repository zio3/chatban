// #180: 認証を廃止したので、発言者は「クライアントの自己申告」だけになった。
// もともと auth.ts にあった pickSpeaker を、認証に依存しない形でここへ移した。
//
// **判断を1か所に置く構えは残す。**かつてメインチャットとタスクチャットで別々に
// 発言者を決めていて、片方だけ保存していなかったことがある (#126)。
// 入口ごとに書き分けると必ずズレる (#92 #108 #114 #125 と同じ形) ので、
// 判断の本体はここに置き、express の Request からは切り離しておく
// (DBもHTTPも要らない純粋関数なので、そのままユニットテストできる)。

/** 発言者名を決める。オブジェクトや空文字など、名前として使えないものは「名乗っていない」扱い。
 *
 * ログイン由来の本人確認 (旧 speaker_email) は #180 で無くなった。
 * いまここに入るのは常に自己申告で、検証されたものではない。
 *
 * 「人間か、エージェントか」の2値は**まだ入れていない**。チャットに書き込む経路が
 * UIしかなく (MCPは chat_messages を書かない)、値が常に「人間」になって意味を持たないため。
 * エージェント側の書き手ができた時点で、ここに足す。 */
export function pickSpeaker(selfReported: unknown): { name: string | null } {
  return {
    name: typeof selfReported === "string" && selfReported.trim() !== "" ? selfReported : null,
  };
}
