/** #186: これを超えたら「太ってきた」と知らせる。
 *
 * 前提情報は**生データと文脈に載るものが同一**で、他 (完了カード→畳んだ完了の箱、経緯メモ→遅延読み込み、
 * ボード状態→基準スナップショット+差分) のような蒸留の段がない。だから放っておくと太る一方になる。
 *
 * 実測 (2026-08-17): プロジェクト#1 が 3,162文字まで育ち、**中身の7割が終わったイベント**だった
 * (提出要件・ブース当日の機材・服装)。白Tにアロハを羽織る話が毎回のプロンプトに載っていた。
 *
 * イベント駆動 (「終わったら見直す」) にしないのは、**そのイベントを人間が覚えていないと機能しない**ため。
 * 実際、終了から2日経っても掃除されなかった。しきい値なら勝手に発火する。 */
const CONTEXT_SIZE_HINT = 2000;

/** 前提情報について気づいてほしいことを知らせる。何も無ければ null (=何も渡さない)。
 *
 * リファレンス全文はここでは返さない。毎回の足場取得に乗せないため、
 * 「足りないものがある」とだけ言い、中身は reference=true で引かせる2段階にする (zio案)。
 *
 * **自動で削るところまではやらない (#186)。** 何が古いかの判定は文脈の話なのでLLMの仕事で、
 * 消す確定は人間の仕事。コードがやるのは「太っている」という**観測を出すところまで**。 */
export function contextTemplateHint(
  text: string
): { missing?: string[]; note?: string; size?: string } | null {
  const missing = TEMPLATE_SECTIONS.filter((h) => !text.includes(h));
  const tooLong = text.length > CONTEXT_SIZE_HINT;
  if (missing.length === 0 && !tooLong) return null;
  return {
    ...(missing.length > 0
      ? {
          missing,
          note: "この前提情報には上の節が無い。get_project_context を reference=true で呼ぶと書き方の参考が取れるので、このプロジェクトに合うものを選んで足せる",
        }
      : {}),
    ...(tooLong
      ? {
          size:
            `${text.length}文字ある (目安 ${CONTEXT_SIZE_HINT}文字)。` +
            "この前提情報はボードのチャットでは毎回のプロンプトに丸ごと載る (MCPでは版だけが返り、本文はこの道具でしか取れない) ので、" +
            "**終わった予定・無くなった機能への言及・過ぎた日付**が残っていないか読み返し、古くなった記述の追い出しを提案すること。" +
            "消すかどうかを決めるのは人間なので、勝手に消さず候補を挙げて確認する",
        }
      : {}),
  };
}

export function contextReference(): string {
  return CONTEXT_REFERENCE;
}