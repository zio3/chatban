import assert from "node:assert/strict";
import test from "node:test";
import fs from "node:fs";
import { CONTEXT_TEMPLATE } from "./contextTemplate.js";
import { toolArgSchemas } from "./toolArgs.js";

/** #261: **前提情報に置いてよいのは「盤を変えたら変わること」だけ。**
 *
 * 実測すると、`1-chatban` の前提情報 1,765字 / 18段落のうち、
 * **盤を変えても変わらないもの (製品の仕様・行動ルール) が16段落**あった。
 * うち4段落はシステムプロンプトに**逐語で同じ文**が入っていた
 * (「前提不足で保留 (◯◯が必要)」「『今やりたい』は逆に上へ」
 * 「依頼か相談か迷ったら相談として扱う」、添付の扱いの段落)。
 *
 * **16段落すべてが他所にあったわけではない** (Codexレビュー P2-4)。分けると:
 *
 *   - **他所に同じ説明があり、消したもの** — 削除・並べ替え・期限・依存・
 *     `context`/`summary`・検索の順路・相談の扱い・Review経由の検収 など
 *   - **他所に無いので、システムプロンプトへ移したもの** — 番号打鍵の案内 (下の1件目)、
 *     Done箱が24時間ぶんであること・板から降りても `archived` で引けること・
 *     実体を消せるのはゴミ箱画面だけであること
 *
 * **後者を「内部の仕様だから捨てる」と書いていたが、それは誤りだった** (2周目 P2-2)。
 * 「完了したカードはいつ消えるのか」「完全に消せるのか」は**利用者から実際に聞かれること**で、
 * 知らなければ答えが変わる。捨てずに移した。
 *
 * ## なぜ二重で持つと困るか — 安さの話ではない (#258)
 *
 * 前提情報は**盤ごとのDBの行**なので、コードの番人がどれも届かない。
 * #232 の移行ガードは識別子、#233/#238 の番人はソースの文言、
 * `promptStale.test.ts` は既定値の載ったプロンプトしか見ていない。
 * コード側は番人に守られているぶん直りやすいので、**同じことを両方に書いたとき、
 * 腐って残るのはたいてい届かない側**になる。実際に3件そうなった:
 * `search_tasks` / `update_task_context` (#260) と、`理由欄` (#179 で廃止した
 * `reason` の日本語名。`promptStale` の `REMOVED` に名指しであるのに、
 * DBの行だけ生き残っていた)。
 *
 * **だから番人を足すのではなく、腐る場所のほうを無くす** (#260 は却下)。
 * ここはその状態を保つための見張り (件数は書かない — 増えたときに黙って嘘になる)。 */

/** 移設したものが消えていないか。**`buildSystemPrompt()` を呼ばずにソースを読む** —
 * あれは `store.ts` 経由で日常用の管理DBを開く (#265 の当の問題) */
const chatSource = fs.readFileSync(new URL("./chat.ts", import.meta.url), "utf-8");

/** **断片では否定を締め出せない** (3周目レビュー P2)。
 *
 * 1周目は語を2つ見て「番号だけでは開けない」に素通りされ、2周目は断片を4つに増やしたが
 * **否定文でも4つとも満たせた**。3周目は肯定形 `/打てば開く/` と否定語3つの排除にしたが、
 * **「打てば開くわけではない」で両方すり抜ける**。
 *
 * **自然言語の否定は列挙し切れない。**「増やして塞ぐ」を3周続けて、抜け道の向きは
 * 一度も変わらなかった。**承認した1文をそのまま置く。**
 *
 * この行は前提情報から移してきた**唯一の移設先**なので、文言が変わったら人が見るべきもの。
 * **文面を直すときは、ここも一緒に直すのが正しい手順** (落ちるのは事故ではなく合図)。 */
const NUMBER_KEY_LINE =
  '"- カードの中身を見たいと言われたら、チャットに番号だけ(`193` / `#193`)を打てば開くと案内してよい。' +
  "LLMを呼ばずに詳細が出る(文中の `#193` はクリックでも開き、アーカイブ済みのものも開ける)。\",";

test("番号打鍵の案内はシステムプロンプト側にある (前提情報から移した #261)", () => {
  assert.ok(
    chatSource.includes(NUMBER_KEY_LINE),
    "番号打鍵の案内が、承認した文面から変わっている。前提情報から移した先はここだけなので、" +
      "消えても薄まってもどこにも無くなる。**文面を直したのなら、このテストの期待値も一緒に直すこと**"
  );
});

/** 番号打鍵と同じく前提情報から移してきたもの。**利用者から実際に聞かれること**
 * (「完了したカードはいつ消えるのか」「完全に消せるのか」) の答えなので、消えると答えが変わる。
 *
 * こちらは**既存の行動ルールに追記した**形なので、行ごと固定はしない (既存部分の推敲で落ちる)。
 * 代わりに**行を特定してから、その行の中で**見る — ファイル全体から拾うと、
 * `archived` のように**他の場所 (`chat.ts` のスキーマ説明) にも出てくる語**が
 * 当の案内から消えても通ってしまう (3周目レビュー P3)。 */
function ruleLine(marker: string): string {
  const line = chatSource.split("\n").find((l) => l.trim().startsWith('"- ') && l.includes(marker));
  assert.ok(line, `行動ルールから「${marker}」の行が消えている`);
  return line!;
}

test("完了カードの行方が、done の行動ルールに書いてある (#261)", () => {
  const line = ruleLine("勝手に done にしない");
  assert.ok(line.includes("24時間"), "「畳んだ完了」の箱が何のまとまりかが消えている。「いつ消えるのか」に答えられない");
  assert.ok(line.includes("archived"), "板から降りても消えていないことが、この案内から消えている");
  assert.ok(line.includes("search_cards"), "あとから引ける手段が消えている");
});

test("実体削除の限界が、削除の行動ルールに書いてある (#261)", () => {
  const line = ruleLine("delete_cards");
  assert.ok(
    line.includes("実体を消せるのはゴミ箱画面"),
    "完全削除の手段が自分に無いことが消えている。無いと「消しました」と言いかねない"
  );
});

/** 新しい盤に配る雛形に、**ツールの名前が出てこない**ことだけを見る。
 *
 * **「ツールの使い方を説明しない」までは見ていない** (Codexレビュー P2-3)。
 * 名前を使わずに「カードを並べ替えるには…」と書き戻せるので、この検査では通ってしまう。
 * 名前に絞るのは、**名前だけが改名で腐る**から — #260 で実際に起きたのは
 * `search_tasks` / `reorder_tasks` / `update_task_context` という**名前**の取りこぼしだった。
 *
 * **雛形の他の節については何も主張しない。**この時点の雛形には
 * `## できなかったとき・やらないとき` (保留・却下・誤登録) が残っていて、そこは
 * 盤ごとに変わらない — #266 で別途落とす。ここが見ているのは名前だけ。
 *
 * 一覧は手書きにせず `toolArgSchemas` のキーから取る。手書きだと**新しく増えたツールを
 * 追随しない**ので、増えた直後だけ穴が開く。`toolArgs.ts` は Zod だけのモジュールで、
 * 読み込んでもDBを開かない。
 *
 * **ただし全部は取れない。**`toolArgSchemas` は引数を検査する道具の一覧なので、
 * **引数を取らない `get_project_context` と `sync_board` は載っていない** (MCP専用でもある)。
 * その2つだけは名指しで足す — ここも増えたら手で足すことになるが、
 * **「引数の無いツール」は滅多に増えない**ので、9件を自動で追う価値のほうが大きい。 */
const TOOL_NAMES = [...Object.keys(toolArgSchemas([])), "get_project_context", "sync_board"];

test("前提情報の雛形にツールの名前が出てこない", () => {
  assert.ok(TOOL_NAMES.length >= 11, `ツール名が${TOOL_NAMES.length}件しか取れていない。検査が素通りする`);
  for (const name of TOOL_NAMES) {
    assert.ok(
      !CONTEXT_TEMPLATE.includes(name),
      `雛形に「${name}」が出ている。ツールの名前は盤を変えても変わらないので契約側の仕事で、` +
        `雛形に入れると新しい盤の数だけ増え、改名したときに全部が腐る (#260 で実際に起きた)`
    );
  }
});
